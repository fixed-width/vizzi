import assert from 'node:assert/strict';
import {callRanges} from './call-ranges.js';
const id=n=>n.toString(16).padStart(64,'0');
const line={number:4,text:'// 🙂 run(); other.run();',left:false,right:false};
const at=(n,start,end,name='run')=>({id:id(n),name,position:{line:4,start,end},binding:null});
assert.deepEqual(callRanges(line,[at(2,21,24),at(1,8,11)]).map(r=>[r.id,r.start,r.end]),[[id(1),8,11],[id(2),21,24]]);
assert.equal(callRanges(line,[at(1,8,11),at(1,8,11)]).length,1);
for(const bad of [at(1,8,10),at(1,4,5),at(1,-1,2),at(1,8,99),at(1,8,8,''),at(1,8.5,11),at(1,8,11.5),at(1,NaN,11),{...at(1,8,11),position:null},{...at(1,8,11),id:1},{...at(1,8,11),id:'fake'},{...at(1,8,11),id:'g'.repeat(64)},{...at(1,8,11),position:{line:5,start:8,end:11}},at(1,8,11,'other'),at(1,4,5,'�')])assert.equal(callRanges(line,[bad]).length,0);
assert.equal(callRanges({...line,left:true},[at(1,8,11)]).length,0);
assert.equal(callRanges({...line,right:true},[at(1,8,11)]).length,1);
assert.equal(callRanges(line,[at(1,8,11),at(2,8,11)]).length,0);
assert.equal(callRanges({number:4,text:'foobar'},[at(1,0,4,'foob'),at(2,3,6,'bar')]).length,0);
assert.equal(callRanges({number:4,text:'abcdefgh'},[at(1,0,6,'abcdef'),at(2,2,3,'c'),at(3,5,8,'fgh')]).length,0);
assert.equal(callRanges({number:4,text:'abcdefgh'},[at(1,0,2,'ab'),at(2,4,6,'ef'),at(3,1,8,'bcdefgh')]).length,0);
assert.equal(callRanges(line,[{...at(1,8,11),id:'1'.repeat(63)},at(1,-1,2,'')]).length,0);
assert.equal(callRanges(line,[{...at(1,8,11),id:null},{...at(1,4,5),name:undefined}]).length,0);
assert.equal(callRanges({number:4,text:'run'},[at(1,0,4)]).length,0);
assert.equal(callRanges({number:4,text:'a'.repeat(234)},[at(1,1,234,'a'.repeat(233)),at(1,12,34,'a'.repeat(22))]).length,0);
assert.deepEqual(callRanges({number:4,text:'foobar'},[at(1,0,3,'foo'),at(2,3,6,'bar')]).map(r=>r.start),[0,3]);
console.log('call ranges: exact Unicode byte identifiers, repetition, clipping, malformed metadata, ambiguity and adjacent ranges');
