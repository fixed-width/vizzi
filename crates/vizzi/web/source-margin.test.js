import assert from 'node:assert/strict';
import {functionIndent,sourceMargin} from './source-margin.js';
assert.equal(functionIndent({text:'    fn process() {'}),4);
assert.equal(functionIndent({text:'\t  def process():'}),6);
assert.equal(functionIndent({text:'  \tfn process() {'}),4);
assert.equal(functionIndent({text:'fn process() {'}),0);
assert.equal(functionIndent({text:'    ',right:true}),0);
assert.equal(functionIndent({text:'    '}),0);
assert.equal(functionIndent({text:'    fn process() {',left:true}),0);
assert.deepEqual(sourceMargin({text:'        run();'},4),{bytes:8,columns:4});
assert.deepEqual(sourceMargin({text:'\t\trun();'},4),{bytes:2,columns:4});
assert.deepEqual(sourceMargin({text:'\t\trun();'},6),{bytes:2,columns:2});
assert.deepEqual(sourceMargin({text:'  \trun();'},3),{bytes:3,columns:1});
assert.deepEqual(sourceMargin({text:'  run();'},4),{bytes:2,columns:0});
assert.deepEqual(sourceMargin({text:'\trun();',left:true},4),{bytes:0,columns:0});
for(const baseline of [-1,NaN,Infinity,1.5])assert.deepEqual(sourceMargin({text:'    run();'},baseline),{bytes:0,columns:0});
assert.deepEqual(sourceMargin({text:'    run();'},0),{bytes:0,columns:0});
console.log('source margin: fixed visual columns, tabs, mixed indentation, short prefixes and clipped/invalid fallback');
for(const value of [null,undefined,{}, {text:1},{text:null}])assert.equal(functionIndent(value),0);
