import assert from 'node:assert/strict';
import {lineRange,checkedRange,checkAudit} from './packs-support.mjs';
import {prompt,systemPrompt,schemaFor} from './model.mjs';
import {createHash} from 'node:crypto';
const bytes=Buffer.from('a界\r\nb\nlast');
assert.deepEqual(lineRange(bytes,1,1),{start:0,end:6});
assert.deepEqual(lineRange(bytes,2,3),{start:6,end:12});
for(const [first,last]of [[0,1],[2,1],[1,4],[1.5,2],[1,NaN]])assert.throws(()=>lineRange(bytes,first,last));
const descriptor={path:'a.rs',first:1,last:1,sha256:createHash('sha256').update(bytes).digest('hex'),content:'f'.repeat(64)};
assert.deepEqual(checkedRange(bytes,descriptor),{path:'a.rs',content:'f'.repeat(64),start:0,end:6});
assert.throws(()=>checkedRange(Buffer.from('changed'),descriptor),/source changed/);
assert.throws(()=>checkedRange(bytes,{...descriptor,path:'../a.rs'}));
assert.throws(()=>checkedRange(bytes,{...descriptor,content:'invalid'}));
const item={id:'case',required_facts:[{text:'HIDDEN_GOLD',evidence:[{path:'a.rs',needle:'guard'}]}],supporting_evidence:[{path:'b.rs',needle:'caller'}]};
const context={snapshot:'version',evidence:[{label:1,path:'a.rs',text:'complete guard\n',start_line:1,end_line:1},{label:2,path:'b.rs',text:'caller()',start_line:1,end_line:1}]};
assert.equal(checkAudit(item,context).complete,true);
assert.throws(()=>checkAudit(item,{...context,evidence:context.evidence.slice(0,1)}),/caller/);
assert.throws(()=>checkAudit(item,{...context,evidence:[{path:'a.rs',text:'missing'},context.evidence[1]]}),/guard/);
const base=prompt({repository:'r',question:'where?'},context,{protocol:'ids',wordLimit:100});
const long=prompt({repository:'r',question:'where?'},context,{protocol:'ids',wordLimit:300});
assert.equal(base[1].content,long[1].content);
assert.equal(long[0].content,base[0].content.replace('100 words','300 words'));
assert.equal(prompt({repository:'r',question:'where?'},context)[0].content,systemPrompt);
assert.ok(!JSON.stringify(long).includes('HIDDEN_GOLD'));
for(const wordLimit of [0,301,1.5,NaN])assert.throws(()=>prompt({repository:'r',question:'where?'},context,{wordLimit}));
assert.equal(schemaFor('ids',8).properties.citations.maxItems,8);
assert.equal(schemaFor('quotes').properties.citations.maxItems,4);
for(const count of [0,9,1.5])assert.throws(()=>schemaFor('ids',count));
console.log('source packs: exact UTF-8/CRLF ranges, immutable files, audit linkage and isolated answer allowance');
