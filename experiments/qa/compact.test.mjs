import assert from 'node:assert/strict';
import {prompt,schemaFor,systemPrompt} from './model.mjs';
import {json,validateLibrary,templatesPath,anchors,digest,libraryPath} from './support.mjs';
import {selectedCases,captureHashes,verifyHashes} from './compact-support.mjs';
import {mkdtemp,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const library=validateLibrary(await json('experiments/qa/library/v2/cases.json'),await json(templatesPath));
const cohort=await json('experiments/qa/library/v2/cohort.json');
assert.equal(library.cases.length,40);
assert.equal(library.parent_sha256,await digest(libraryPath),'preserve the v1 seed');
const parent=await json(libraryPath);
assert.equal(library.cases.filter(c=>c.origin_id).length,parent.cases.length);
assert.ok(library.cases.filter(c=>c.origin_id).every(c=>c.split==='development' && parent.cases.some(p=>p.id===c.origin_id)));
assert.equal(library.cases.filter(c=>c.split==='held_out').length,8);
assert.equal(cohort.case_ids.length,23);
assert.equal(new Set(cohort.case_ids).size,23);
assert.ok(cohort.case_ids.every(id=>library.cases.some(c=>c.id===id)));
assert.ok(library.cases.filter(c=>c.split==='held_out').every(c=>cohort.case_ids.includes(c.id)));
const item={repository:'fixture',question:'What is the retry limit?',required_facts:[{text:'HIDDEN_GOLD_SENTINEL',evidence:[{path:'hidden.rs',needle:'HIDDEN_GOLD_SENTINEL'}]}],supporting_evidence:[{path:'caller.rs',needle:'caller'}]};
assert.deepEqual(anchors(item),[['hidden.rs','HIDDEN_GOLD_SENTINEL'],['caller.rs','caller']]);
const context={snapshot:'snapshot',evidence:[{label:1,path:'config.toml',start_line:1,end_line:1,text:'retry_limit = 7',role:'configuration',role_basis:'path_convention',scope:null}]};
const quote=prompt(item,context,{protocol:'quotes',metadata:true});
const ids=prompt(item,context,{protocol:'ids',metadata:true});
assert.equal(quote[1].content,ids[1].content,'citation ablation must use identical evidence text and metadata');
assert.ok(ids[0].content.includes('integer source labels'));
assert.ok(!ids[0].content.includes('exact quotations'));
assert.equal(prompt(item,context)[0].content,systemPrompt,'legacy prompt remains the control');
for(const messages of [quote,ids,prompt(item,context)])assert.ok(!JSON.stringify(messages).includes('HIDDEN_GOLD_SENTINEL'));
assert.equal(schemaFor('ids').properties.citations.items.type,'integer');
assert.equal(schemaFor('quotes').properties.citations.items.type,'object');
assert.deepEqual(Object.keys(schemaFor('ids').properties),['status','answer','citations']);
assert.deepEqual(schemaFor('ids').properties.status,schemaFor('quotes').properties.status);
assert.deepEqual(schemaFor('ids').properties.answer,schemaFor('quotes').properties.answer);
assert.throws(()=>schemaFor('unknown'));
assert.equal(selectedCases(library,'development').length,32);
assert.equal(selectedCases(library,'held_out').length,8);
assert.throws(()=>selectedCases(library,'all'));
const directory=await mkdtemp(join(tmpdir(),'vizzi-qa-freeze-test-'));
try{
 const file=join(directory,'input');await writeFile(file,'before');
 const hashes=await captureHashes([file]);await verifyHashes(hashes);
 await writeFile(file,'after');await assert.rejects(verifyHashes(hashes),/frozen input changed/);
}finally{await rm(directory,{recursive:true});}
console.log('compact experiment: versioned cohort, no gold leakage, identical compact contexts, isolated citation schema');
